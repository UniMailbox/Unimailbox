-- migrations/0008_webhook_events.sql — CAP-024 Brevo webhook delivery.
-- Adds webhook_deliveries (one row per received provider event) and a
-- per-connection webhook_secret used to HMAC-verify the raw body before
-- JSON parse (R-INBOUND-SIGNATURE; .claude/rules/architecture.md §API
-- conventions, .claude/rules/security.md §Secrets).
--
-- Rules enforced:
--   R-INBOUND-SIGNATURE: signature verification runs before JSON parse.
--   R-DATA-004: PRAGMA foreign_keys = ON (D1 default).
--
-- Migration tracking (F1): the INSERT OR IGNORE INTO d1_migrations makes
-- apply+track atomic with the schema change.
--
-- R-DATA-005 explicit exception: webhook_deliveries.raw_payload is a TEXT
-- column that stores the verbatim JSON body the provider sent. Justified
-- the same way as audit_events.metadata (0001_initial.sql): the raw
-- payload is the canonical audit record of the provider event and is
-- preserved unmodified for replay / forensic analysis. Capped at 64 KB
-- via CHECK — providers (Brevo, Resend, CF) ship webhooks well under
-- that bound. Sized to match the audit_events.metadata cap so the
-- exception pattern is uniform across the schema.

-- Per-connection HMAC secret. Generated by ensureWebhookSecret on first
-- read; NULL until then. Stored as plaintext because it is a random
-- signing key (not a user-chosen password and not a provider API key).
ALTER TABLE provider_connections ADD COLUMN webhook_secret TEXT;

CREATE TABLE IF NOT EXISTS webhook_deliveries (
  id              TEXT PRIMARY KEY,
  connection_id   TEXT NOT NULL REFERENCES provider_connections(id) ON DELETE CASCADE,
  event_type      TEXT NOT NULL,
  raw_payload     TEXT NOT NULL CHECK (length(raw_payload) <= 65536),
  message_id      TEXT REFERENCES messages(id) ON DELETE SET NULL,
  status          TEXT NOT NULL DEFAULT 'processed',
  created_at      TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS webhook_deliveries_connection_idx ON webhook_deliveries(connection_id);
CREATE INDEX IF NOT EXISTS webhook_deliveries_created_idx ON webhook_deliveries(created_at DESC);

INSERT OR IGNORE INTO d1_migrations (name) VALUES ('0008_webhook_events.sql');
